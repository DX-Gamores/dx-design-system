#!/usr/bin/env node
// Brand gallery: themes/<slug>.json (theme-builder settings) → CSS, DTCG JSON, React Native and a summary for the site.
//   node --experimental-strip-types scripts/build-brands.mjs
// Outputs (committed; CI checks they are fresh):
//   dist/brands/<slug>.css · <slug>.tokens.json · <slug>.native.ts · gallery.json, and dist/brands.css (every brand, for the site)
// Fails when a brand doesn't pass the 27-pair contrast audit in all four colour modes (gate G3).
import fs from "node:fs";
import path from "node:path";
import { buildBrand, fontPackages, toCss, toDtcg, toNative } from "../src/lib/theme/engine.ts";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const vars = JSON.parse(fs.readFileSync(path.join(root, "figma/variables.raw.json"), "utf8"));
const builtIn = new Set(["default", "violet", "amber"]);
const out = path.join(root, "dist/brands");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const files = fs.existsSync(path.join(root, "themes")) ? fs.readdirSync(path.join(root, "themes")).filter((f) => f.endsWith(".json")).sort() : [];
const gallery = [];
let css = "/* DX brand gallery — generated by scripts/build-brands.mjs from themes/*.json. Do not edit by hand. */\n";
const failures = [];
for (const f of files) {
  const { $comment, ...input } = JSON.parse(fs.readFileSync(path.join(root, "themes", f), "utf8"));
  const b = buildBrand(vars, input);
  if (`${b.slug}.json` !== f) failures.push(`themes/${f}: the file name must be the brand's slug (${b.slug}.json)`);
  if (builtIn.has(b.slug)) failures.push(`themes/${f}: “${b.slug}” is a built-in brand name`);
  if (b.passed !== b.total) {
    const bad = Object.entries(b.audit).flatMap(([m, rows]) => rows.filter((r) => !r.pass).map((r) => `${m} ${r.fg} on ${r.bg} ${r.ratio}:1 < ${r.min}:1`));
    failures.push(`${b.input.name}: ${b.passed}/${b.total} contrast pairs pass\n    ${bad.join("\n    ")}`);
  }
  fs.writeFileSync(path.join(out, `${b.slug}.css`), toCss(b));
  fs.writeFileSync(path.join(out, `${b.slug}.tokens.json`), toDtcg(b));
  fs.writeFileSync(path.join(out, `${b.slug}.native.ts`), toNative(vars, b));
  css += "\n" + toCss(b);
  gallery.push({ slug: b.slug, name: b.input.name, input: b.input, ramps: b.ramps, roles: b.roles, notes: b.notes, passed: b.passed, total: b.total, fonts: fontPackages(b.input), comment: $comment ?? "" });
}
fs.writeFileSync(path.join(root, "dist/brands.css"), css);
fs.writeFileSync(path.join(out, "gallery.json"), JSON.stringify(gallery, null, 1) + "\n");
if (failures.length) {
  console.error("✗ Brand gallery:\n  " + failures.join("\n  "));
  process.exit(1);
}
console.log(`✓ ${gallery.length} gallery brand${gallery.length === 1 ? "" : "s"} (${gallery.map((g) => `${g.slug} ${g.passed}/${g.total}`).join(", ")}) → dist/brands/, dist/brands.css`);
