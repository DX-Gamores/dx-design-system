#!/usr/bin/env node
// Builds code-ready design tokens from the Figma export in /figma.
//   node scripts/build-tokens.mjs
// Outputs (committed, so apps can consume them without running this):
//   tokens/tokens.json      W3C DTCG format, every mode kept
//   dist/tokens.css         CSS variables + theme switching (brand, theme, density, motion, breakpoints)
//   dist/tailwind.css       Tailwind v4 @theme mapping + text-style utilities
//   dist/tokens.ts          Typed JS object for charts and runtime use
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const vars = read("figma/variables.raw.json");
const { textStyles, effectStyles } = read("figma/styles-components.raw.json");

const col = Object.fromEntries(vars.map((c) => [c.n, c]));
const slug = (name) => name.replace(/\//g, "-").replace(/\s+/g, "-").toLowerCase();
const cssVar = (name) => `--ds-${slug(name)}`;
const typeOf = { C: "color", F: "number", S: "string" };

// ---------- value helpers
const isAlias = (v) => typeof v === "string" && v.startsWith("@");
const px = (name, v) => {
  if (typeof v !== "number") return v;
  if (/^(opacity)\//.test(name)) return String(v / 100);
  if (/^(z|layout\/columns|font-weight|spring)\b|stiffness|damping/.test(name)) return String(v);
  if (/^(duration|spring\/.*\/duration)/.test(name)) return `${v}ms`;
  if (/^layout\/breakpoint/.test(name)) return `${v}px`;
  if (/^letter-spacing/.test(name)) return `${Math.round(v * 100) / 100}px`;
  if (name === "radius/full") return "9999px";
  return `${Math.round(v * 100) / 100}px`;
};
const fontWeight = { Regular: 400, Medium: 500, "Semi Bold": 600, SemiBold: 600, Bold: 700 };
const value = (name, v) => {
  if (isAlias(v)) return `var(${cssVar(v.slice(1))})`;
  if (name.startsWith("font-style/")) return String(fontWeight[v] ?? 400);
  if (name.startsWith("font-family/")) {
    const fallback = name.endsWith("mono") ? "ui-monospace, SFMono-Regular, Menlo, monospace" : "ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif";
    return `"${v}", ${fallback}`;
  }
  return px(name, v);
};
const block = (selector, entries) => `${selector} {\n${entries.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
const modeEntries = (c, i) => c.v.map(([n, , vals]) => [cssVar(n.replace(/^font-style\//, "font-weight/")), value(n, vals[i])]);

// ---------- CSS
let css = `/* DX Design System — generated by scripts/build-tokens.mjs. Do not edit by hand. */\n/* Usage: <html data-brand="default|violet|amber" data-theme="light|dark|light-hc|dark-hc" data-density="comfortable|compact">\n   Set data-brand and data-theme on the SAME element (usually <html>). */\n\n`;
css += block(":root", modeEntries(col.Primitives, 0));
// Brand
const brandSel = { 0: ':root, [data-brand="default"]', 1: '[data-brand="violet"]', 2: '[data-brand="amber"]' };
col.Brand.m.forEach((_, i) => (css += block(brandSel[i], modeEntries(col.Brand, i))));
// Color modes
const themeSel = ['light', 'dark', 'light-hc', 'dark-hc'];
css += block(':root, [data-theme="light"]', [...modeEntries(col.Color, 0), ["color-scheme", "light"]]);
css += block('[data-theme="dark"]', [...modeEntries(col.Color, 1), ["color-scheme", "dark"]]);
css += block('[data-theme="light-hc"]', [...modeEntries(col.Color, 2), ["color-scheme", "light"]]);
css += block('[data-theme="dark-hc"]', [...modeEntries(col.Color, 3), ["color-scheme", "dark"]]);
css += `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', [...modeEntries(col.Color, 1), ["color-scheme", "dark"]]).replace(/^/gm, "  ")}}\n`;
css += `@media (prefers-contrast: more) {\n${block(':root:not([data-theme])', modeEntries(col.Color, 2)).replace(/^/gm, "  ")}}\n`;
// Density
css += block(':root, [data-density="comfortable"]', modeEntries(col.Dimension, 0));
css += block('[data-density="compact"]', modeEntries(col.Dimension, 1));
// Typography (Desktop default, Tablet < 1024, Mobile < 600)
css += block(":root", modeEntries(col.Typography, 0));
css += `@media (max-width: 1023px) {\n${block(":root", modeEntries(col.Typography, 1)).replace(/^/gm, "  ")}}\n`;
css += `@media (max-width: 599px) {\n${block(":root", modeEntries(col.Typography, 2)).replace(/^/gm, "  ")}}\n`;
// Layout (Desktop default; Tablet, Mobile, Wide)
css += block(":root", modeEntries(col.Layout, 0));
css += `@media (max-width: 1023px) {\n${block(":root", modeEntries(col.Layout, 1)).replace(/^/gm, "  ")}}\n`;
css += `@media (max-width: 599px) {\n${block(":root", modeEntries(col.Layout, 2)).replace(/^/gm, "  ")}}\n`;
css += `@media (min-width: 1440px) {\n${block(":root", modeEntries(col.Layout, 3)).replace(/^/gm, "  ")}}\n`;
// Motion
css += block(':root, [data-motion="default"]', modeEntries(col.Motion, 0));
css += block('[data-motion="reduced"]', modeEntries(col.Motion, 1));
css += `@media (prefers-reduced-motion: reduce) {\n${block(':root:not([data-motion])', modeEntries(col.Motion, 1)).replace(/^/gm, "  ")}}\n`;
// Component + Effects (single mode)
css += block(":root", [...modeEntries(col.Component, 0), ...modeEntries(col.Effects, 0)]);
// Effect styles -> shadows
const shadow = (e) =>
  [...e.e].reverse().map((s) => `${s.x || 0}px ${s.y || 0}px ${s.r || 0}px ${s.sp || 0}px var(${cssVar(s.c)})`).join(", ");
const effects = effectStyles.map((e) => [`--ds-shadow-${slug(e.n)}`, shadow(e)]);
css += block(":root, [data-theme]", effects);
// Text styles -> utility classes
const ts = textStyles.map((t) => {
  const b = t.bv;
  const decl = [
    ["font-family", b.fontFamily ? `var(${cssVar(b.fontFamily)})` : `"${t.f}"`],
    ["font-weight", b.fontStyle ? `var(${cssVar(b.fontStyle.replace("font-style/", "font-weight/"))})` : fontWeight[t.w] ?? 400],
    ["font-size", b.fontSize ? `var(${cssVar(b.fontSize)})` : `${t.s}px`],
    ["line-height", b.lineHeight ? `var(${cssVar(b.lineHeight)})` : `${t.lh}px`],
  ];
  if (b.letterSpacing) decl.push(["letter-spacing", `var(${cssVar(b.letterSpacing)})`]);
  return [slug(t.n), decl];
});
css += "\n/* Text styles — same names as Figma (Heading/H1 → .ds-heading-h1) */\n";
for (const [n, d] of ts) css += block(`.ds-${n}`, d);
css += block(":where(:focus-visible)", [["outline", "none"], ["box-shadow", "var(--ds-shadow-focus-ring)"]]);
fs.mkdirSync(path.join(root, "dist"), { recursive: true });
fs.writeFileSync(path.join(root, "dist/tokens.css"), css);

// ---------- Tailwind v4 mapping
const colorNames = col.Color.v.map(([n]) => n);
const tw = [];
for (const n of colorNames) {
  const v = `var(${cssVar(n)})`;
  let m;
  if ((m = n.match(/^color\/bg\/(.+)$/))) tw.push([`--color-${m[1]}`, v]);
  else if ((m = n.match(/^color\/text\/(.+)$/))) tw.push([`--color-fg-${m[1]}`, v]);
  else if ((m = n.match(/^color\/border\/(.+)$/))) tw.push([`--color-line-${m[1]}`, v]);
  else if ((m = n.match(/^color\/icon\/(.+)$/))) tw.push([`--color-icon-${m[1]}`, v]);
  else if ((m = n.match(/^color\/dataviz\/(.+)$/))) tw.push([`--color-viz-${m[1]}`, v]);
  else if ((m = n.match(/^color\/category\/(.+)$/))) tw.push([`--color-cat-${m[1].replace(/\//g, "-")}`, v]);
  else if ((m = n.match(/^color\/shadow\/(.+)$/))) tw.push([`--color-shadow-${m[1]}`, v]);
}
for (const k of ["sm", "md", "lg", "xl", "full"]) tw.push([`--radius-${k}`, `var(--ds-radius-${k})`]);
tw.push(["--radius-control", "var(--ds-shape-radius-control)"], ["--radius-container", "var(--ds-shape-radius-container)"]);
for (const e of effectStyles) tw.push([`--shadow-${slug(e.n).replace("elevation-", "elevation-")}`, `var(--ds-shadow-${slug(e.n)})`]);
tw.push(["--font-heading", "var(--ds-font-family-heading)"], ["--font-body", "var(--ds-font-family-body)"], ["--font-sans", "var(--ds-font-family-body)"], ["--font-mono", "var(--ds-font-family-mono)"]);
for (const [n] of col.Typography.v.filter(([n]) => n.startsWith("font-size/"))) {
  const k = n.split("/")[1];
  tw.push([`--text-${k}`, `var(--ds-font-size-${k})`], [`--text-${k}--line-height`, `var(--ds-line-height-${k})`]);
}
for (const k of ["standard", "enter", "exit", "spring-snappy", "spring-gentle", "spring-bouncy"]) tw.push([`--ease-${k}`, `var(--ds-easing-${k})`]);
for (const k of ["sm", "md", "lg"]) tw.push([`--spacing-control-${k}`, `var(--ds-size-control-${k})`]);
let twcss = `/* DX Design System — Tailwind v4 theme. Generated. */\n/* In app/globals.css:  @import "tailwindcss";  @import "@dxform/design-system/tokens.css";  @import "@dxform/design-system/tailwind.css"; */\n\n@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *, [data-theme="dark-hc"], [data-theme="dark-hc"] *));\n\n`;
twcss += `@theme inline {\n${tw.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n\n`;
twcss += "/* Text styles as utilities: class=\"text-heading-h1\" */\n";
for (const [n, d] of ts) twcss += `@utility text-${n} {\n${d.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
twcss += `@utility focus-ring {\n  outline: none;\n  box-shadow: var(--ds-shadow-focus-ring);\n}\n`;
twcss += `@utility h-control-sm {\n  height: var(--ds-size-control-sm);\n}\n@utility h-control-md {\n  height: var(--ds-size-control-md);\n}\n@utility h-control-lg {\n  height: var(--ds-size-control-lg);\n}\n`;
fs.writeFileSync(path.join(root, "dist/tailwind.css"), twcss);

// ---------- DTCG JSON
const dtcg = { $description: "DX Design System tokens (W3C DTCG). Exported from Figma. Aliases use {group.name}." };
const setPath = (obj, parts, leaf) => {
  let o = obj;
  for (const p of parts.slice(0, -1)) o = o[p] ??= {};
  o[parts[parts.length - 1]] = leaf;
};
const ref = (v) => (isAlias(v) ? `{${v.slice(1).replace(/\//g, ".")}}` : v);
for (const c of vars) {
  const group = (dtcg[c.n] ??= { $description: `Modes: ${c.m.join(", ")}` });
  for (const [n, t, vals] of c.v) {
    const leaf = { $type: typeOf[t] === "number" ? "number" : typeOf[t], $value: ref(vals[0]) };
    if (c.m.length > 1) leaf.$extensions = { "com.figma.modes": Object.fromEntries(c.m.map((m, i) => [m, ref(vals[i])])) };
    setPath(group, n.split("/"), leaf);
  }
}
dtcg.textStyles = Object.fromEntries(textStyles.map((t) => [t.n, { $type: "typography", $value: { fontFamily: t.f, fontWeight: fontWeight[t.w], fontSize: `${t.s}px`, lineHeight: `${t.lh}px`, letterSpacing: `${t.ls}px` } }]));
dtcg.effectStyles = Object.fromEntries(effectStyles.map((e) => [e.n, { $type: "shadow", $value: e.e.map((s) => ({ offsetX: `${s.x}px`, offsetY: `${s.y}px`, blur: `${s.r}px`, spread: `${s.sp}px`, color: `{${s.c.replace(/\//g, ".")}}` })) }]));
fs.mkdirSync(path.join(root, "tokens"), { recursive: true });
fs.writeFileSync(path.join(root, "tokens/tokens.json"), JSON.stringify(dtcg, null, 2));

// ---------- TS object (runtime: charts, canvas, emails)
const jsVar = (n) => `var(${cssVar(n)})`;
const ts_ = `// Generated. Theme-aware CSS variable references for runtime use (charts, canvas, inline styles).\nexport const dataviz = {\n  series: [${[1, 2, 3, 4, 5, 6, 7, 8].map((i) => `"${jsVar("color/dataviz/series-" + i)}"`).join(", ")}],\n  sequential: [${[1, 2, 3, 4, 5].map((i) => `"${jsVar("color/dataviz/sequential-" + i)}"`).join(", ")}],\n  diverging: [${["neg-2", "neg-1", "mid", "pos-1", "pos-2"].map((k) => `"${jsVar("color/dataviz/diverging-" + k)}"`).join(", ")}],\n  gridline: "${jsVar("color/dataviz/gridline")}",\n  axis: "${jsVar("color/dataviz/axis")}",\n  label: "${jsVar("color/dataviz/label")}",\n} as const;\n\nexport const brands = ["default", "violet", "amber"] as const;\nexport const themes = ["light", "dark", "light-hc", "dark-hc"] as const;\nexport const densities = ["comfortable", "compact"] as const;\nexport type Brand = (typeof brands)[number];\nexport type Theme = (typeof themes)[number];\nexport type Density = (typeof densities)[number];\n\n/** Read a token's current value (after theme switching) — e.g. for canvas charts. */\nexport function readToken(name: string, el: Element = document.documentElement) {\n  return getComputedStyle(el).getPropertyValue(name.startsWith("--") ? name : "--ds-" + name.replace(/\\//g, "-")).trim();\n}\n`;
fs.writeFileSync(path.join(root, "dist/tokens.ts"), ts_);

const count = vars.reduce((a, c) => a + c.v.length, 0);
console.log(`✓ ${count} variables, ${textStyles.length} text styles, ${effectStyles.length} effect styles → dist/tokens.css, dist/tailwind.css, dist/tokens.ts, tokens/tokens.json`);
